export type FreeRoomsDictionary = typeof freeRoomsDictionary

export function weekdayShortLabel(t: Translator<FreeRoomsDictionary>, day: number): string {
  switch (day) {
    case 1:
      return t("weekdayShort.1")
    case 2:
      return t("weekdayShort.2")
    case 3:
      return t("weekdayShort.3")
    case 4:
      return t("weekdayShort.4")
    case 5:
      return t("weekdayShort.5")
    case 6:
      return t("weekdayShort.6")
    case 7:
      return t("weekdayShort.7")
    default:
      return String(day)
  }
}

