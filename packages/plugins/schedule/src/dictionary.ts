export type ScheduleDictionary = typeof scheduleDictionary

export function translatePatchOperation(
  t: Translator<ScheduleDictionary>,
  mode: SchedulePatch["mode"]
): string {
  switch (mode) {
    case "copy":
      return t("scheduleEditor.operation_copy")
    case "move":
      return t("scheduleEditor.operation_move")
    case "clear":
      return t("scheduleEditor.operation_clear")
  }
}

export function translatePatchIssue(
  t: Translator<ScheduleDictionary>,
  reason: ScheduleIssue["reason"]
): string {
  switch (reason) {
    case "invalidDate":
      return t("scheduleEditor.issue_invalidDate")
    case "invalidSections":
      return t("scheduleEditor.issue_invalidSections")
    case "missingDependency":
      return t("scheduleEditor.issue_missingDependency")
    case "dependencyCycle":
      return t("scheduleEditor.issue_dependencyCycle")
    case "sourceMissing":
      return t("scheduleEditor.issue_sourceMissing")
    case "sourceChanged":
      return t("scheduleEditor.issue_sourceChanged")
    case "sourceAmbiguous":
      return t("scheduleEditor.issue_sourceAmbiguous")
    case "targetChanged":
      return t("scheduleEditor.issue_targetChanged")
    case "patchConflict":
      return t("scheduleEditor.issue_patchConflict")
    case "targetOverlap":
      return t("scheduleEditor.issue_targetOverlap")
    case "alreadyApplied":
      return t("scheduleEditor.issue_alreadyApplied")
  }
}

export function formatScheduleEditorError(
  t: Translator<ScheduleDictionary>,
  error: unknown
): string {
  if (!(error instanceof Error)) return t("scheduleEditor.saveFailed")
  if (error.message === "scheduleEditor.notReady") return t("scheduleEditor.notReady")
  if (error.message.startsWith("scheduleEditor.issue_")) {
    const reason = error.message.slice("scheduleEditor.issue_".length)
    switch (reason) {
      case "invalidDate":
      case "invalidSections":
      case "missingDependency":
      case "dependencyCycle":
      case "sourceMissing":
      case "sourceChanged":
      case "sourceAmbiguous":
      case "targetChanged":
      case "patchConflict":
      case "targetOverlap":
      case "alreadyApplied":
        return translatePatchIssue(t, reason)
      default:
        return error.message
    }
  }
  return error.message || t("scheduleEditor.saveFailed")
}

